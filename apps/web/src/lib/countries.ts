/** Origens mais comuns nas lojas de Ciudad del Este, mostradas primeiro na lista. */
export const COMMON_ORIGINS = ["CN", "PY", "US", "TW", "KR", "JP", "VN", "BR", "DE", "MY", "TH", "IN"] as const;

const SET = new Set<string>(COUNTRY_CODES);

export function isCountryCode(code: string | null | undefined): boolean {
  return Boolean(code) && SET.has(code!.trim().toUpperCase());
}

export function countryName(code: string, locale: string): string {
  try {
    return new Intl.DisplayNames([locale], { type: "region" }).of(code.toUpperCase()) ?? code;
  } catch {
    return code;
  }
}

/** Opções para o select: as origens comuns primeiro e as demais em ordem alfabética no idioma da página. */
export function countryOptions(locale: string): Array<{ code: string; name: string; common: boolean }> {
  const collator = new Intl.Collator(locale);
  const common = COMMON_ORIGINS.map((code) => ({ code, name: countryName(code, locale), common: true }));
  const rest = COUNTRY_CODES.filter((c) => !(COMMON_ORIGINS as readonly string[]).includes(c))
    .map((code) => ({ code, name: countryName(code, locale), common: false }))
    .sort((a, b) => collator.compare(a.name, b.name));
  return [...common, ...rest];
}
